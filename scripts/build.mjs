/**
 * Caelum Orbis build.
 *
 * Two outputs, no other toolchain:
 *   index.js   Host half — ESM bundle for Node, loaded by the Cordis Loader row.
 *   client.js  Browser half — bundled CJS body wrapped in the DSH ModuleLoader
 *              envelope, with `react` left external because the page provides it.
 *
 * Run with `node scripts/build.mjs` (or `pnpm build`).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

const shared = {
  bundle: true,
  logLevel: 'warning',
  // Keep the `/*! … */` license headers of bundled dependencies (three, zustand).
  // Their MIT terms require the notice to travel with the distributed copies, and
  // dropping it made the published artifact non-compliant.
  legalComments: 'eof',
  define: { 'process.env.NODE_ENV': '"production"' },
  absWorkingDir: root,
};

/** Version banner: the artifact must be able to say which build it is. */
const banner = (half) =>
  `/* ${pkg.name} ${pkg.version} — ${half} half. Generated by scripts/build.mjs; do not edit. */`;

/**
 * Third-party attribution.
 *
 * `legalComments` alone is not enough: it only preserves comments esbuild already
 * recognises as legal ones (`/*!`, `@license`, `@preserve`), and neither three.js
 * nor zustand ships such a header — their terms live in a separate LICENSE file
 * that the bundler never sees. Injecting the notice here is what actually makes
 * the distributed bundle MIT-compliant; `THIRD-PARTY-NOTICES.md` carries the full
 * texts. `react` is absent on purpose: the page supplies it, we never bundle it.
 */
const THIRD_PARTY_NOTICE = `/*! Bundled third-party code:
 *   three.js — MIT, Copyright © 2010-2026 three.js authors
 *   zustand  — MIT, Copyright (c) 2019 Paul Henschel
 * Full license texts: THIRD-PARTY-NOTICES.md in this package.
 */`;

async function buildHost() {
  const result = await build({
    ...shared,
    entryPoints: [join(root, 'src/host/index.ts')],
    outfile: join(root, 'index.js'),
    format: 'esm',
    platform: 'node',
    target: ['node20'],
    sourcemap: false,
    banner: { js: banner('host') },
  });
  if (result.errors.length > 0) throw new Error('host build failed');
  return join(root, 'index.js');
}

async function buildClient() {
  const result = await build({
    ...shared,
    entryPoints: [join(root, 'src/client/index.tsx')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    jsx: 'transform',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    // The page's module table owns React; everything else is bundled.
    external: ['react'],
    minify: true,
    metafile: true,
  });
  const output = result.outputFiles?.[0];
  if (output === undefined) throw new Error('client build produced no output');

  const body = output.text
    .split('\n')
    .map((line) => (line === '' ? '' : `      ${line}`))
    .join('\n');

  const wrapped = `${banner('browser')}
${THIRD_PARTY_NOTICE}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
    (function (module, exports, require) {
${body}
    })(module, exports, require);
    return module.exports;
  },
});
`;

  const target = join(root, 'client.js');
  await writeFile(target, wrapped, 'utf8');
  return { target, bytes: Buffer.byteLength(wrapped), inputs: Object.keys(result.metafile?.inputs ?? {}).length };
}

async function main() {
  const host = await buildHost();
  const client = await buildClient();
  const hostBytes = Buffer.byteLength(await readFile(host, 'utf8'));
  const report = [
    `host   index.js   ${(hostBytes / 1024).toFixed(1)} kB`,
    `client client.js  ${(client.bytes / 1024).toFixed(1)} kB  (${client.inputs} modules)`,
  ].join('\n');
  process.stdout.write(`${report}\n`);
}

await main();
